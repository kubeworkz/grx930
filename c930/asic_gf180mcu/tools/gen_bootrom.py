"""Generate grx930_test_chip_rom.sv -- the boot ROM -- from a firmware hex.

    python3 tools/gen_bootrom.py [HEX] [OUT_SV]

Both defaults are resolved relative to THIS FILE, not the current directory, so the
script runs from anywhere and needs no arguments in a clone:

    c930/sw/test_chip_boot.hex                                      (the input)
    c930/asic_gf180mcu/openlane2_rtl/src/grx930_test_chip_rom.sv    (the output)

The hex is itself a build product: `make fw` in c930/asic_gf180mcu rebuilds it from
c930/sw/test_chip_boot.S with c930/sw/build_test_chip_fw.sh (RISC-V toolchain), and
the checked-in hex is the current build. So the chain to a netlist ROM is
.S -> .hex -> .sv, and the .sv is committed rather than generated at flow time
because the flow's Yosys run reads a file list and does not run generators.

tools/gen_bootrom_selftest.sh is the check that keeps that honest: it regenerates
and fails if the committed .sv is not a byte-for-byte reproduction, if the defaults
drift onto other paths, or if the output stops depending on the input.

Why a generated constant-ROM instead of a memory with initial contents: the
GF180MCU standard-cell libraries have no ROM macro, and a `reg [63:0] mem []`
with an `initial` block relies on yosys carrying per-flop init values through
`memory_map`/`techmap` into the netlist -- OpenROAD then treats those as
simulation-only attributes, so silicon would power up with an empty ROM. A
constant `case` is pure combinational logic and is guaranteed to appear in the
netlist and in the layout.

Interface timing mirrors grx930_sram_64kb exactly, because the I-cache fill
path (and the top-level mux between the two memories) depends on it:

  * request cycle T   : address presented
  * cycle T+1         : line registered (SRAM: rd_word[] loaded), held after
  * cycle T+2         : o_rd_done pulses
  * cycle T+3         : the I-cache controller writes the line it sampled --
                        one cycle AFTER the done pulse, which is why the line
                        must be HELD (a combinational ROM output is already
                        gone by then and the cache stores X).

Layout must match the SRAM's: word j of a line occupies bits [32*j +: 32] of
the 256-bit line, i.e. o_rd_line bit 8*i is byte i of the 32-byte line, and the
hex file supplies 32-bit little-endian words at consecutive addresses from 0.

With -DROM_DISABLE the ROM reads as zeros: the negative control for the boot
test (a core that resets into ROM then fetches zeros and cannot boot).
"""
import os
import sys

ROM_BASE = 0x1_0000      # 0x0001_0000, the address the chip resets to
ROM_BYTES = 1024         # 1 KB = 32 x 32-byte lines
LINE_BYTES = 32
WORDS_PER_LINE = LINE_BYTES // 4

DEFAULT_HEX = os.path.join(os.path.dirname(__file__), "..", "..", "sw",
                           "test_chip_boot.hex")
DEFAULT_OUT = os.path.join(os.path.dirname(__file__), "..", "openlane2_rtl",
                           "src", "grx930_test_chip_rom.sv")


def read_hex(path):
    words = []
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            words.append(int(line, 16) & 0xFFFFFFFF)
    return words


def main(hex_path, out_path):
    words = read_hex(hex_path)
    lines = ROM_BYTES // LINE_BYTES
    nimg = (len(words) + WORDS_PER_LINE - 1) // WORDS_PER_LINE
    if nimg > lines:
        sys.exit(
            f"ERROR: image needs {nimg} lines ({len(words)*4} bytes), "
            f"ROM has {lines} ({ROM_BYTES} bytes)"
        )

    body = []
    for ln in range(lines):
        val = 0
        used = 0
        for j in range(WORDS_PER_LINE):
            idx = ln * WORDS_PER_LINE + j
            if idx < len(words):
                val |= words[idx] << (32 * j)
                used += 1
        body.append(
            f"        5'd{ln}: rom_line = 256'h{val:064x};"
            + (f"  // line {ln}: {used} word(s)" if used else "")
        )

    rel_hex = os.path.relpath(hex_path, os.path.dirname(os.path.abspath(DEFAULT_OUT)))
    text = f"""// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 Gridworkz
// GENERATED by tools/gen_bootrom.py from {rel_hex.replace(os.sep, '/')} -- do not edit.
//
// grx930_test_chip_rom: the chip's boot source. {len(words)*4} bytes of firmware
// ({nimg} of {lines} lines used) at {ROM_BASE:#x}, read through the same 2-cycle,
// 256-bit-line interface as the SRAM, so the I-cache fill path needs only an
// address-range mux (see grx930_test_chip.sv).
//
// Two properties are load-bearing and mirror grx930_sram_64kb:
//   * the line is registered one cycle after the request and HELD until the next
//     access -- the I-cache controller registers its write enable from the done
//     pulse, so it samples the line one cycle AFTER o_rd_done;
//   * the constant table is combinational logic (no memory init), because a
//     flop-init ROM would not survive synthesis into a real layout.
`default_nettype none

module grx930_test_chip_rom #(
    parameter logic [63:0] ROM_BASE = 64'h{ROM_BASE:016x},
    parameter int          AW       = 10            // 1 KB = 2**AW bytes
) (
    input  logic         i_clk,
    input  logic         i_rst_n,
    input  logic [63:0]  i_rd_addr,
    output logic [255:0] o_rd_line,
    output logic         o_rd_done
);

  localparam int LINES = 2 ** (AW - 5);           // 32-byte lines

  logic          hit_p1, hit_p2;
  logic [AW-6:0] line_p1;
  logic [255:0]  rd_line_r;

  wire hit = (i_rd_addr[63:AW] == ROM_BASE[63:AW]);

  // The constant table with -DROM_DISABLE zeroed (negative control).
  function automatic logic [255:0] rom_line(input logic [AW-6:0] l);
`ifdef ROM_DISABLE
    rom_line = 256'b0;   // negative control: no firmware anywhere
`else
    case (l)
{chr(10).join(body)}
      default: rom_line = 256'b0;
    endcase
`endif
  endfunction

  always_ff @(posedge i_clk or negedge i_rst_n) begin
    if (!i_rst_n) begin
      hit_p1    <= 1'b0;
      hit_p2    <= 1'b0;
      line_p1   <= '0;
      rd_line_r <= '0;
    end else begin
      hit_p1  <= hit;
      line_p1 <= i_rd_addr[AW-1:5];
      hit_p2  <= hit_p1;
      if (hit_p1)
        rd_line_r <= rom_line(line_p1);   // held until the next access
    end
  end

  assign o_rd_line = rd_line_r;
  assign o_rd_done = hit_p2;

endmodule

`default_nettype wire
"""
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", newline="\n") as f:
        f.write(text)
    print(
        f"wrote {out_path}: {len(words)} words ({len(words)*4} bytes), "
        f"{nimg}/{lines} lines, ROM_BASE={ROM_BASE:#x}"
    )


if __name__ == "__main__":
    hex_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_HEX
    out_path = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    main(hex_path, out_path)
