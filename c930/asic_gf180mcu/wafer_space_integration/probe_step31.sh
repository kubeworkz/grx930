# probe_step31.sh -- container side: rerun ONLY the step that killed ws_v2
# (OpenROAD.RepairDesignPostGPL) against ws_v2's own frozen pre-repair state, so
# a wrong knob costs 30-60 min instead of another full flow.
#
# Nothing upstream is redone. LibreLane's --only/-T machinery takes an explicit
# initial state file, and ws_v2's step 30 state_out.json still points at
# 27-openroad-globalplacement/chip_top.odb -- the exact ODB step 31 read when it
# failed with DPL-0036. So synthesis, floorplan, PDN and global placement are all
# skipped and the comparison is direct: same input ODB, same step, new knobs.
#
#   PROBE_TAG=ws_v3_probe        fresh run tag for the probe tree
#   PROBE_STATE_TAG=ws_v2        run whose step 30 state to start from
#
# The knobs themselves are *not* passed with -c here: they are read from the
# staged librelane/grx930_overrides.yaml, so this tests the file that the real
# run will use rather than a copy of it. The script prints them so the log
# records what was actually tested.
set -u
cd /work/ws/template || exit 1

# Normally written by the template's `make defines`; written here because the
# flow is driven directly (same as ws_exec.sh).
printf '// generated by probe_step31.sh\n`define SLOT_1X1\n`define SRAM_gf180mcu_fd_ip_sram\n' \
    > src/generated_defines.svh

STATE=/work/ws/template/librelane/runs/${PROBE_STATE_TAG:-ws_v2}/30-openroad-stamidpnr/state_out.json
TAG=${PROBE_TAG:-ws_v3_probe}

echo "PROBE: tag=$TAG"
echo "PROBE: librelane $(librelane --version 2>&1 | head -1)"
echo "PROBE: initial state $STATE"
echo "PROBE: the state's ODB, as the step will see it:"
grep -o '"odb": "[^"]*"' "$STATE"
echo "PROBE: knobs in the staged overrides --"
grep -nE "^(PL_MAX_DISPLACEMENT|DESIGN_REPAIR|RUN_POST_GPL)" librelane/grx930_overrides.yaml

librelane --pdk gf180mcuD --pdk-root /workspace/gf180mcu \
    --manual-pdk --scl gf180mcu_fd_sc_mcu7t5v0 --pad gf180mcu_fd_io \
    --run-tag "$TAG" --only OpenROAD.RepairDesignPostGPL -i "$STATE" \
    librelane/slots/slot_1x1.yaml \
    librelane/macros/macros_5v.yaml \
    librelane/config.yaml \
    librelane/grx930_overrides.yaml
echo "PROBE_EXIT:$?"
