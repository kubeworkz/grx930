#!/bin/sh
# ws_exec.sh -- container side: run the wafer.space template flow with the grx930
# core inside it, in the pre-check image (LibreLane >= 3 + the gf180mcuD PDK).
#
# Launch it as the image's *command*, not through /bin/sh, so the image's
# entrypoint (scripts/dev-shell) wraps it in the nix development shell that has
# librelane, ciel, klayout, magic and coreutils:
#
#   docker run --rm --user 0:0 -v /home/ubuntu/grx930_ol2:/work \
#       -e WS_TAG=ws_v1 ghcr.io/wafer-space/gf180mcu-precheck /work/ws/ws_exec.sh
#
#   WS_TAG=ws_v1           run tag -- must be FRESH: resuming a tag reuses that
#                          tag's netlist, and the RTL has changed since any old run
#   WS_LIMIT=<Step>        optional -T (stop after this step); e.g.
#                          WS_LIMIT=Checker.LintWarnings for a parse-only run
#   PDK_ROOT               defaults to the image's PDK (/workspace/gf180mcu)
#
# Everything not set here comes from the staged tree, unmodified from the
# template: slots/slot_1x1.yaml (pad ring, DIE/CORE area), macros/macros_5v.yaml
# (pad + ws_ip macros), config.yaml (PDN, SDC, clock port/net), and
# grx930_overrides.yaml (this design: sources, density, routing knobs).
set -u
cd /work/ws/template || exit 1

# Normally written by the template's `make defines`; written here because the
# flow is driven directly.
printf '// generated by ws_exec.sh\n`define SLOT_1X1\n`define SRAM_gf180mcu_fd_ip_sram\n' \
    > src/generated_defines.svh

echo "WS_EXEC: tag=${WS_TAG:-ws_v1} limit=${WS_LIMIT:-none} pdk_root=${PDK_ROOT:-/workspace/gf180mcu}"
echo "WS_EXEC: librelane $(librelane --version 2>&1 | head -1)"
echo "WS_EXEC: core sources: $(ls asic_core/*.sv | wc -l) files; chip_core.sv $(wc -l < src/chip_core.sv) lines"

if [ -n "${WS_LIMIT:-}" ]; then
    librelane --pdk gf180mcuD --pdk-root "${PDK_ROOT:-/workspace/gf180mcu}" \
        --manual-pdk --scl gf180mcu_fd_sc_mcu7t5v0 --pad gf180mcu_fd_io \
        --run-tag "${WS_TAG:-ws_v1}" -T "$WS_LIMIT" \
        librelane/slots/slot_1x1.yaml \
        librelane/macros/macros_5v.yaml \
        librelane/config.yaml \
        librelane/grx930_overrides.yaml
else
    librelane --pdk gf180mcuD --pdk-root "${PDK_ROOT:-/workspace/gf180mcu}" \
        --manual-pdk --scl gf180mcu_fd_sc_mcu7t5v0 --pad gf180mcu_fd_io \
        --run-tag "${WS_TAG:-ws_v1}" \
        librelane/slots/slot_1x1.yaml \
        librelane/macros/macros_5v.yaml \
        librelane/config.yaml \
        librelane/grx930_overrides.yaml
fi
echo "WS_EXIT:$?"
