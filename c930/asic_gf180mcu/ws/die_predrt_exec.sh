#!/bin/sh
# die_predrt_exec.sh -- container side: build the DIE's pre-DRT database at the
# landed GRT_ADJUSTMENT (0.1), by resuming ws_v3's frozen step-36 state into a
# fresh run tag and running the Chip flow from GlobalRouting through STAMidPNR-3.
#
# Why STAMidPNR-3 and not the antenna repair: between RepairAntennas (step 42 in
# the image's Chip flow) and DetailedRouting (step 45) sit RepairDesignPostGRT
# (gated off by RUN_POST_GRT_DESIGN_REPAIR: false), ResizerTimingPostGRT (gated
# off by RUN_POST_GRT_RESIZER_TIMING: false) and STAMidPNR-3 -- and LibreLane
# hands DetailedRouting whatever ODB the LAST executed step's state_out.json
# names. STA steps pass the ODB through, so that file is the antenna-repaired
# database, but the chain reads the path out of the state file rather than
# guessing a step ordinal: that is the file the router would read.
#
# Why GlobalRouting is re-run (~4 min) instead of skipped: ws_v3 died INSIDE
# step 37 and never wrote its state_out, so the newest GRT-complete state on disk
# is the pre-GRT one. -i takes that state -- the same ODB every GRT probe
# consumed -- and re-running the step with the staged file is exactly the landed
# test the probes made (it converged: 0 overflow on every layer, 8 iterations).
#
# The host chain (build/die_drt_chain.sh) gates on the GRT step's own log naming
# "Global adjustment: 10%" before it spends hours on DRT: a silently different
# value would make the DRT arm a different datum, not this one.
#
#   PREDRT_TAG       fresh run tag (default die01)
#   PREDRT_STATE     state to resume from (default ws_v3 step 36 state_out.json)
#   PREDRT_STOP      last step to run (default OpenROAD.STAMidPNR-3). Set to
#                    OpenROAD.DetailedRouting to carry the run into the router
#                    itself, which is what "the flow reaches detailed routing"
#                    means when the step before it has to succeed first.
#   PREDRT_OR        an alternative OpenROAD binary for this run, exported as
#                    _LLN_OVERRIDE_OPENROAD (LibreLane's own hook: openroad.py
#                    OpenROADStep.get_openroad_path). Used to run the whole flow
#                    under a build that has the FastRoute fixes the pinned image
#                    lacks -- e.g. /work/ws/tools/openroad_26q4.sh.
#   PREDRT_OVERRIDE  optional single config override for this run only
#                    (KEY=VALUE, JSON value), passed as `-c` BEFORE the config
#                    files. Used for RUN_ANTENNA_REPAIR=false: the unmodified
#                    run dies inside OpenROAD.DiodeInsertion (the antenna-repair
#                    composite's own global-router pass) with GRT-0183 on this
#                    pinned build, so the die cannot insert antenna diodes at
#                    0.1 at all. The staged file is never edited: the override
#                    is visible in the run's own resolved.json, which is how the
#                    measurement stays honest about its arm.
#   PREDRT_PATCH_LLN=1023
#                    optional: backport LibreLane PR #1023's io.tcl scene
#                    handling into the installed LibreLane IN THIS CONTAINER
#                    before the flow starts (ws/tools/librelane_1023_io_patch.py).
#                    Required by the engine pin: with the 26Q4 OpenROAD in place
#                    the GRT step completes and then the step dies as it finishes
#                    with `[ERROR STA-0107] ..._p_Scene is not the name of a
#                    scene` -- this image's LibreLane (3.1.0.dev1) predates #1023,
#                    which 3.0.13 shipped. The patch is per-container (the image
#                    is untouched): a fresh die_predrt container starts unpatched.
set -u
TAG=${PREDRT_TAG:-die01}
STATE=${PREDRT_STATE:-/work/ws/template/librelane/runs/ws_v3/36-openroad-stamidpnr-2/state_out.json}
LOG=/work/ws/logs/predrt_$TAG.log
[ -f "$STATE" ] || { echo "PREDRT: no state at $STATE" >&2; exit 1; }
mkdir -p /work/ws/logs
cd /work/ws/template || exit 1

# Normally written by the template's `make defines` / ws_exec.sh; the steps in
# this range do not read the RTL, but the config lists these sources and a
# missing file would make the resume fail for a reason unrelated to routing.
printf '// generated by die_predrt_exec.sh\n`define SLOT_1X1\n`define SRAM_gf180mcu_fd_ip_sram\n' \
    > src/generated_defines.svh

{
    echo "PREDRT_START tag=$TAG"
    echo "PREDRT state=$STATE"
    echo "PREDRT override=${PREDRT_OVERRIDE:-none}"
    echo "PREDRT librelane $(librelane --version 2>&1 | head -1)"
    echo "PREDRT openroad $(command -v openroad) $(openroad -version 2>&1 | head -1)"
    echo "PREDRT stop=${PREDRT_STOP:-OpenROAD.STAMidPNR-3}"
    if [ -n "${PREDRT_OR:-}" ]; then
        export _LLN_OVERRIDE_OPENROAD="$PREDRT_OR"
        echo "PREDRT openroad_override=$_LLN_OVERRIDE_OPENROAD $($PREDRT_OR -version 2>&1 | head -1)"
    else
        echo "PREDRT openroad_override=none"
    fi
    echo "PREDRT knobs as staged (the file the flow resolves) --"
    grep -nE "^(GRT_ADJUSTMENT|DRT_OPT_ITERS|RT_MIN_LAYER|RUN_POST_GRT_DESIGN_REPAIR|RUN_POST_GRT_RESIZER_TIMING|RUN_ANTENNA_REPAIR):" librelane/grx930_overrides.yaml
} > "$LOG"

# Engine-pin prerequisite (opt-in): LibreLane #1023's io.tcl scene fix. The
# GRT step completes on the 26Q4 build and then dies as it finishes with
# `[ERROR STA-0107] ..._p_Scene is not the name of a scene` -- this image's
# LibreLane predates #1023, so without this the pin arm never leaves step 01.
# Refusing to run when the patch did not apply is deliberate: a pin arm that
# silently fell back to the old scene handling would die 30 minutes in and look
# like an engine failure.
if [ "${PREDRT_PATCH_LLN:-}" = 1023 ]; then
    PYP=$(command -v python3 2>/dev/null || true)
    if [ -z "${PYP:-}" ]; then
        for c in /nix/store/*-python3-3.13.9/bin/python3.13; do
            [ -x "$c" ] && { PYP=$c; break; }
        done
    fi
    "$PYP" /work/ws/tools/librelane_1023_io_patch.py >> "$LOG" 2>&1 || true
    if grep -qE "^PATCH_LLN status=(applied|already-patched)" "$LOG"; then
        echo "PREDRT_PATCH_LLN ok" >> "$LOG"
    else
        echo "PREDRT_PATCH_LLN_FAILED -- refusing the pinned run without the backport" >> "$LOG"
        exit 1
    fi
fi

# Line-buffered step logs (ws/tools/lln_logflush.sh). Without it the DRT step's log
# reaches this file only every 8 KB, and the curve guard cannot see an iteration
# that stops printing until its 2 h wall clock -- the failure measured on diecg01,
# where 182 lines arrived in one flush after 42 minutes of silence.
. /work/ws/tools/lln_logflush.sh >> "$LOG" 2>&1

set --
[ -n "${PREDRT_OVERRIDE:-}" ] && set -- -c "$PREDRT_OVERRIDE"

librelane --pdk gf180mcuD --pdk-root "${PDK_ROOT:-/workspace/gf180mcu}" \
    --manual-pdk --scl gf180mcu_fd_sc_mcu7t5v0 --pad gf180mcu_fd_io \
    --run-tag "$TAG" -F OpenROAD.GlobalRouting -T "${PREDRT_STOP:-OpenROAD.STAMidPNR-3}" \
    -i "$STATE" "$@" \
    librelane/slots/slot_1x1.yaml \
    librelane/macros/macros_grx930.yaml \
    librelane/config.yaml \
    librelane/grx930_overrides.yaml >> "$LOG" 2>&1
rc=$?
echo "PREDRT_EXIT:$rc" >> "$LOG"
exit $rc
