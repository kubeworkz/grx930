# ws_exec.sh -- container side: run the wafer.space template flow with the grx930
# core inside it, in the pre-check image (LibreLane >= 3 + the gf180mcuD PDK).
#
# Launch it as the image's *command*, not through /bin/sh, so the image's
# entrypoint (scripts/dev-shell) wraps it in the nix development shell that has
# librelane, ciel, klayout, magic and coreutils:
#
#   docker run --rm --user 0:0 -v /home/ubuntu/grx930_ol2:/work \
#       -e WS_TAG=ws_v1 ghcr.io/wafer-space/gf180mcu-precheck /work/ws/ws_exec.sh
#
#   WS_TAG=ws_v1           run tag -- must be FRESH: resuming a tag reuses that
#                          tag's netlist, and the RTL has changed since any old run
#   WS_LIMIT=<Step>        optional -T (stop after this step); e.g.
#                          WS_LIMIT=Checker.LintWarnings for a parse-only run
#   WS_FROM=<Step>         optional -F (continue an existing tag at this step).
#                          Name the step AFTER the last one that finished: -F
#                          re-runs the step it names, and the state it hands that
#                          step is the tag's latest state_out.json -- naming the
#                          step that produced that state feeds it its own output:
#                          tag sram02 resumed at GeneratePDN, pdngen saw a grid
#                          already in the odb and inserted a second rail set
#                          (57 s -> 15 min and 9 GB before it was killed; that
#                          run is recorded in wafer_space_integration/
#                          sram_macro_surrogate.md).
#   PDK_ROOT               defaults to the image's PDK (/workspace/gf180mcu)
#
# Everything not set here comes from the staged tree: slots/slot_1x1.yaml (pad
# ring, DIE/CORE area) and config.yaml (SDC, clock port/net) unmodified from the
# template, and grx930_overrides.yaml (this design: sources, density, routing
# knobs, PDN config).
#
# The macro list is macros_grx930.yaml rather than the template's macros_5v.yaml.
# The template's file also declares the two foundry SRAM macros with instances
# i_chip_core.sram_0 / sram_1, which belong to the demo chip_core.sv it shipped
# with. This design's chip_core has no SRAM macro -- its memory is behavioural RTL
# inferred by synthesis -- so OpenROAD.CheckMacroInstances stops the flow at step
# 11 of 83 with "No macro instance i_chip_core.sram_0 found" (measured, run tag
# ws_v1). macros_grx930.yaml is the template's own ws_ip block (QR, shuttle,
# project, marker, logo -- what --cob needs) with that SRAM entry omitted and
# PDN_MACRO_CONNECTIONS emptied; its header says how to re-sync it.
set -u
cd /work/ws/template || exit 1

# Normally written by the template's `make defines`; written here because the
# flow is driven directly.
printf '// generated by ws_exec.sh\n`define SLOT_1X1\n`define SRAM_gf180mcu_fd_ip_sram\n' \
    > src/generated_defines.svh

echo "WS_EXEC: tag=${WS_TAG:-ws_v1} from=${WS_FROM:-none} limit=${WS_LIMIT:-none} pdk_root=${PDK_ROOT:-/workspace/gf180mcu}"
echo "WS_EXEC: librelane $(librelane --version 2>&1 | head -1)"
echo "WS_EXEC: core sources: $(ls asic_core/*.sv | wc -l) files; chip_core.sv $(wc -l < src/chip_core.sv) lines"
echo "WS_EXEC: macros librelane/macros/macros_grx930.yaml: $(grep -c '^  gf180mcu' librelane/macros/macros_grx930.yaml) declared (expect 5 ws_ip), demo SRAM macro block present: $(grep -c '^  gf180mcu_fd_ip_sram__sram512x8m8wm1:' librelane/macros/macros_grx930.yaml) (expect 0)"

# Line-buffered step logs: a step log that only reaches the disk every 8 KB cannot
# tell a stalled router from a working one, which is what build/drt_curve_guard.sh
# needs to know while DRT runs. Best effort -- see ws/tools/lln_logflush.sh.
. /work/ws/tools/lln_logflush.sh

# Reset nets into CTS: LibreLane passes no -clk_nets, so the reset is never treed
# and reaches the post-CTS resizer as one ~4,266-load net -- load splitting then
# re-drives the same fanout behind a single buffer (measured: `split25`, 2,132
# loads, 21-47 ns transition against a 3 ns limit, and the 8.6 ns STA disagreement
# between the pinned and 26Q4 engines that follows from it). Best effort -- see
# ws/tools/lln_reset_cts.sh.
. /work/ws/tools/lln_reset_cts.sh

# A fanout limit the resizer actually enforces: the same 50 load-split buffers that
# carry 7,409 sinks behind one `buf_12` each are what DRT spends three routes on,
# and repair_timing's splitting answers an over-loaded net with one buffer ahead of
# the same loads instead of bounding it. Opt-in -- WS_FANOUT_SPLIT=1 -- so an arm
# launched without it stays comparable to the runs already on the box. Best effort
# -- see ws/tools/lln_fanout_split.sh.
. /work/ws/tools/lln_fanout_split.sh

# A repair_antennas abort the run can survive: this image's OpenROAD takes the maze
# router into GRT-0183 (heap underflow) on some nets, and the step -- then the run --
# dies with it, which is what ended wave fanout01 before its DRT step ever started
# (2,120 diodes in, on clknet_leaf_2609_clk_PAD2CORE). The catch keeps the diodes
# already inserted and lets the step write its database. Installed by default because
# a repair that completes never enters the branch; WS_ANTENNA_CATCH=0 keeps the old
# fatal behaviour. See ws/tools/lln_antenna_catch.sh.
. /work/ws/tools/lln_antenna_catch.sh

# -F before -T, both before the config files: the same shape sram_surrogate_exec.sh
# uses, so a resumed arm and a fresh one differ only in which flags are set.
set -- librelane --pdk gf180mcuD --pdk-root "${PDK_ROOT:-/workspace/gf180mcu}" \
    --manual-pdk --scl gf180mcu_fd_sc_mcu7t5v0 --pad gf180mcu_fd_io \
    --run-tag "${WS_TAG:-ws_v1}"

if [ -n "${WS_FROM:-}" ]; then
    set -- "$@" -F "$WS_FROM"
fi
# Config keys for this arm only, KEY=VALUE (JSON value), space separated, each
# passed as its own -c BEFORE the config files so they win. Same shape as
# die_predrt_exec.sh's PREDRT_OVERRIDE: a measured lever (GRT_ANTENNA_REPAIR_ITERS=1
# to stay out of the iteration that aborts, GRT_ALLOW_CONGESTION=false to keep the
# maze router inside its budget) is passed without editing the staged tree, so the
# file the next run resolves is still the file the last one resolved. One key per
# -c: LibreLane splits the argument on '=' and rejects a JSON object there.
if [ -n "${WS_OVERRIDE:-}" ]; then
    for ws_kv in $WS_OVERRIDE; do
        set -- "$@" -c "$ws_kv"
    done
fi
if [ -n "${WS_LIMIT:-}" ]; then
    set -- "$@" -T "$WS_LIMIT"
fi

set -- "$@" \
    librelane/slots/slot_1x1.yaml \
    librelane/macros/macros_grx930.yaml \
    librelane/config.yaml \
    librelane/grx930_overrides.yaml

"$@"
echo "WS_EXIT:$?"
