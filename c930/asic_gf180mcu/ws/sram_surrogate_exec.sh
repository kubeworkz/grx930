#!/bin/sh
# sram_surrogate_exec.sh -- container side: run the wafer.space template flow
# with grx930's SRAM built from the foundry macro instead of a flip-flop array
# (scope §7 step 3, the macro-flow surrogate).
#
# Launch it as the image's *command*, so the entrypoint wraps it in the nix
# LibreLane shell:
#
#   docker run --rm --user 0:0 -v /home/ubuntu/grx930_ol2:/work \
#       -e SRAM_TAG=sram01 ghcr.io/wafer-space/gf180mcu-precheck \
#       /work/ws/sram_surrogate_exec.sh
#
#   SRAM_TAG=<tag>     run tag -- must be FRESH unless resuming with SRAM_FROM
#   SRAM_LIMIT=<Step>  optional -T (stop after this step); the first pass stops
#                      at OpenROAD.GeneratePDN, which is as far as the macro
#                      path needs to be proved before the long run is worth it
#   SRAM_FROM=<Step>   optional -F (resume an existing tag at this step)
#   PDK_ROOT           defaults to the image's PDK (/workspace/gf180mcu)
#
# Two differences from ws_exec.sh, both deliberate:
#   * the macro list is macros_grx930_sram.yaml (the ws_ip block plus the eight
#     SRAM instances), passed INSTEAD of macros_grx930.yaml -- see that file's
#     header for why it is a whole copy rather than an addition;
#   * grx930_sram_surrogate.yaml is passed last: it sets USE_SRAM_MACRO and
#     points PDN_CFG at the file with the macro grids.
set -u
cd /work/ws/template || exit 1

# Normally written by the template's `make defines`; written here because the
# flow is driven directly.
printf '// generated by sram_surrogate_exec.sh\n`define SLOT_1X1\n`define SRAM_gf180mcu_fd_ip_sram\n' \
    > src/generated_defines.svh

echo "SRAM_EXEC: tag=${SRAM_TAG:-sram01} limit=${SRAM_LIMIT:-none} from=${SRAM_FROM:-none}"
echo "SRAM_EXEC: librelane $(librelane --version 2>&1 | head -1)"
echo "SRAM_EXEC: macro groups declared: $(grep -c '^  gf180mcu' librelane/macros/macros_grx930_sram.yaml) (expect 6: 5 ws_ip + the SRAM)"
echo "SRAM_EXEC: SRAM instances declared: $(grep -cE 'u_macro_[0-7]:$' librelane/macros/macros_grx930_sram.yaml) (expect 8)"
echo "SRAM_EXEC: surrogate overrides: $(grep -c '^VERILOG_DEFINES:' librelane/grx930_sram_surrogate.yaml) (expect 1)"

# Same two patches the routing runs use, so the comparison is like for like:
# line-buffered step logs (the DRT guards read them) and the reset net into CTS.
. /work/ws/tools/lln_logflush.sh
. /work/ws/tools/lln_reset_cts.sh

set -- librelane --pdk gf180mcuD --pdk-root "${PDK_ROOT:-/workspace/gf180mcu}" \
    --manual-pdk --scl gf180mcu_fd_sc_mcu7t5v0 --pad gf180mcu_fd_io \
    --run-tag "${SRAM_TAG:-sram01}"

if [ -n "${SRAM_FROM:-}" ]; then
    set -- "$@" -F "$SRAM_FROM"
fi
if [ -n "${SRAM_LIMIT:-}" ]; then
    set -- "$@" -T "$SRAM_LIMIT"
fi

set -- "$@" \
    librelane/slots/slot_1x1.yaml \
    librelane/macros/macros_grx930_sram.yaml \
    librelane/config.yaml \
    librelane/grx930_overrides.yaml \
    librelane/grx930_sram_surrogate.yaml

"$@"
echo "SRAM_EXIT:$?"
