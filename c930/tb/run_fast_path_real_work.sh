# run_fast_path_real_work.sh -- the real work the push fast path has to be able to
# finish: build the SoC models and drive the simulations to their own end.
#
# WHY THIS IS NOT THE GATES
#
#   c930/asic_gf180mcu/build/chip_gates.sh asks "can this machine check the
#   design". Every one of its nine gates compiles something small, reads the
#   answer and reports a verdict, and together they are about thirty seconds on
#   the fast path. None of them builds and runs the design. The difference is the
#   one that matters to a canary: a runner can be online, pass every gate, and
#   still be unable to finish a job that asks for a real simulation -- out of
#   disk, out of memory, killed part-way, or reading an input nothing generates
#   any more. Those are red runs that only appear when real work is attempted.
#
# WHAT "REAL WORK" MEANS HERE
#
#   A simulation the repo intends someone to run, started from a clean checkout,
#   with nothing but the fast path's own tools -- iverilog, vvp, make, python3.
#   There is no synthesis tool on that machine, so a netlist, a GDS or a LibreLane
#   run is not available to it; simulation is what it can be asked to finish. Each
#   workload below must build its own model, run to the testbench's own
#   `$finish called at <time>` line, and print the verdict lines it is checked
#   for.
#
# THE WORKLOADS (measured on the fast path, 2026-10-15)
#
#   l2-coherent     ~0s    the shared-L2 refill/hit/write-through/readback and
#                          directory-invalidation test
#   ar-withdraw     ~1s    the DMA arbiter and the crossbar abandon a
#                          granted-but-unaccepted AR (180 checks)
#   quad-four-core  ~25s   the whole SoC -- four harts, DDR, crossbar, APLIC, two
#                          NPUs -- with each hart running its own GEMM, checking
#                          its own C matrix, and the testbench reading all 50 C
#                          elements back out of DDR
#
#   Those times are what an otherwise idle box gives; measured 22s to 52s for the
#   quad workload depending on what else the machine is doing, which is the honest
#   spread for a shared build machine and the reason nothing here asserts a
#   duration.
#
#   The last one is the point of this file: it is the heaviest bounded simulation
#   the fast path's toolchain can run, and it is real in the way a gate is not --
#   the design is elaborated, built into a ~14 MB model, booted, driven and read
#   back, over about 89 us of simulated hardware time.
#
# WHY THE WORKLOAD IS NOT BIGGER THAN THAT
#
#   The heavier c930 targets need tools this machine does not have (Verilator for
#   the four-core SoC suite, a RISC-V toolchain for every firmware-linked test), or
#   are documented in the Makefile itself as unusable under Icarus: `driver_test`
#   is named "NOT RUNNABLE ON THIS HOST" after 48,428 seconds of vvp CPU overnight
#   without printing a single result. A canary that hangs is worse than one that
#   is short, so the workloads here are the ones that finish.
#
# WHY THE IMAGE IS GENERATED HERE
#
#   The quad testbench loads sw/quadcore_ddr_bytes.hex, which is not tracked
#   (.gitignore: c930/sw/*.hex) -- so it is generated by the repo's own
#   sw/gen_quadcore_test.py, with python3 only: that generator emits the
#   instruction encodings itself and needs no RISC-V toolchain. This matters more
#   than tidiness. Without the image the test does not fail fast: it was measured
#   taking 446s to reach "QUAD-ISOLATED FAILED: 54 errors", because the hart
#   firmware is absent from DDR and the testbench waits out its own bound. With
#   it, about 25s to PASS.
#
# WHY IT REMOVES THE MODEL BEFORE IT BUILDS
#
#   Each workload's .vvp is deleted first, so the artefact being present afterwards
#   is evidence that this run compiled the design. CI checks out a fresh workspace
#   and would build regardless; doing it here means a local run says the same
#   thing, instead of reporting a cached binary as a finished build.
#
# WHY IT MAKES c930/build BEFORE CALLING make
#
#   `make quad` (and l2_coherent, ar_withdraw) writes into c930/build without
#   creating it, so from a clean checkout those targets die inside iverilog with
#   `build/tb_quad_isolated.vvp: No such file or directory / error: Code generator
#   failure: -1` -- measured on a pristine `git archive` of main. The other
#   simulation rules in that Makefile do `mkdir -p $(BUILD_DIR)` themselves. This
#   script is a caller, so it creates the directory it is about to build in rather
#   than depending on a make target that never had the dependency.
#
# WHAT THIS DOES NOT PROVE
#
#   Not the gate-level flow, not synthesis, not LibreLane: those tools are not on
#   this machine. Not that a multi-hour job survives either -- these workloads are
#   seconds to a minute, so the honest claim they support is "the fast path can
#   build and finish real simulations", never "the fast path can finish anything
#   you send it".
#
# USAGE
#
#   bash c930/tb/run_fast_path_real_work.sh                  # every workload
#   bash c930/tb/run_fast_path_real_work.sh --list           # names only
#   bash c930/tb/run_fast_path_real_work.sh --only quad-four-core
#
#   REAL_WORK_TIMEOUT=900 bash c930/tb/run_fast_path_real_work.sh
#
# EXIT STATUS
#
#   0 only when every workload built, ran to its own $finish, printed every line
#   it is checked for, and left its model behind. A workload whose tool is missing
#   reports BLOCKED, which is a failure: work that could not run must never read as
#   work that passed. 2 is a usage error (bad flag or unknown workload name).
set -u

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH= cd -- "$HERE/../.." && pwd)          # c930/tb -> repo root
C930="$ROOT/c930"
LOGDIR="$C930/build/real_work"

RUN_TIMEOUT=${REAL_WORK_TIMEOUT:-900}
PREP_TIMEOUT=${REAL_WORK_PREP_TIMEOUT:-120}

# name | prep | make target | artefact | tools | evidence lines (;-separated)
#
# The evidence lines are the literal ones that have to be in the workload's own
# log, matched with grep -F: an exit status alone cannot tell a simulation that
# checked something from one that died on the way in. They are the testbench's
# verdict plus the strongest per-check line it prints, so "the process exited 0"
# is never the whole of the evidence.
WORKLOADS=$(cat <<'EOF'
l2-coherent|-|l2_coherent|build/tb_l2_coherent.vvp|iverilog vvp make timeout|ALL L2 TESTS PASSED
ar-withdraw|-|ar_withdraw|build/tb_ar_withdraw.vvp|iverilog vvp make timeout|ALL AR/AW-WITHDRAW TESTS PASSED (180 checks)
quad-four-core|python3 sw/gen_quadcore_test.py|quad|build/tb_quad_isolated.vvp|iverilog vvp make python3 timeout|QUAD-ISOLATED TEST PASSED;all four cores verified their C matrices on-core;TB readback: all 50 C elements across 4 GEMMs correct
EOF
)

only=()
list_only=0
while [ $# -gt 0 ]; do
  case "$1" in
    --list) list_only=1; shift ;;
    --only)
      [ $# -ge 2 ] || { echo "real_work: --only needs a workload name (see --list)" >&2; exit 2; }
      only+=( "$2" ); shift 2 ;;
    # The header, up to the first line of code, so it cannot go stale half way
    # through a sentence.
    -h|--help) sed -n '2,/^set -u$/p' "$0"; exit 0 ;;
    *) echo "real_work: unknown argument: $1 (try --list or --help)" >&2; exit 2 ;;
  esac
done

in_only() {
  local n
  for n in ${only[@]+"${only[@]}"}; do [ "$n" = "$1" ] && return 0; done
  return 1
}

if [ $list_only -eq 1 ]; then
  while IFS='|' read -r name _rest; do [ -n "$name" ] && echo "$name"; done < <(printf '%s\n' "$WORKLOADS")
  exit 0
fi

# An unknown --only is a usage error, not a run that silently does nothing and
# exits 0: asking for a workload by name and getting no run is the failure the
# name was supposed to rule out.
if [ ${#only[@]} -gt 0 ]; then
  for want in "${only[@]}"; do
    found=0
    while IFS='|' read -r name _rest; do
      [ "$name" = "$want" ] && { found=1; break; }
    done < <(printf '%s\n' "$WORKLOADS")
    [ $found -eq 1 ] || { echo "real_work: no such workload: $want (see --list)" >&2; exit 2; }
  done
fi

# ROOT comes from this file's own path, so it only means anything when the file is
# where it lives. A copy parked elsewhere would resolve to a directory with no
# simulations in it and fail workload by workload for reasons that look like
# simulation failures -- say it once, here, with the path that was computed.
if [ ! -d "$C930/tb" ] || [ ! -f "$C930/Makefile" ]; then
  echo "real_work: ROOT resolved to '$ROOT', which is not this repository." >&2
  echo "           This script is c930/tb/run_fast_path_real_work.sh inside the repo;" >&2
  echo "           a copy somewhere else has no SoC to build." >&2
  exit 2
fi
mkdir -p "$LOGDIR" || { echo "real_work: cannot create $LOGDIR" >&2; exit 2; }
mkdir -p "$C930/build" || { echo "real_work: cannot create $C930/build" >&2; exit 2; }

human_bytes() {  # bytes -> "13 MB" / "812 KB" / "17 B", so a small model reads as small
  local b=$1
  if [ "$b" -ge 1048576 ]; then echo "$((b / 1048576)) MB"
  elif [ "$b" -ge 1024 ]; then echo "$((b / 1024)) KB"
  else echo "$b B"; fi
}

missing_tools() {  # "tool tool ..." -> prints the ones not on PATH, then goes
  local t
  for t in $1; do command -v "$t" >/dev/null 2>&1 || printf '%s ' "$t"; done
}

annotate() {  # message -- a GitHub error annotation when there is a GitHub to read it
  [ "${GITHUB_ACTIONS:-}" = true ] && echo "::error::$1"
  return 0
}

echo "ROOT      $ROOT"
echo "IVERILOG  $( { iverilog -V 2>/dev/null || echo 'not found'; } | head -1)"
echo "LOGS      $LOGDIR/<workload>.log"
echo

fail=0
pass=0
blocked=0
ran=0
seconds=0
rows=""

while IFS='|' read -r name prep target artefact tools evidence; do
  [ -n "$name" ] || continue
  if [ ${#only[@]} -gt 0 ] && ! in_only "$name"; then continue; fi
  ran=$((ran + 1))

  lack=$(missing_tools "$tools")
  if [ -n "$lack" ]; then
    echo "WORK $name: BLOCKED (not on PATH: ${lack% })"
    annotate "$name is BLOCKED: missing ${lack% }"
    rows="${rows}| $name | BLOCKED (missing ${lack% }) | | |
"
    blocked=$((blocked + 1)); fail=1
    continue
  fi

  log="$LOGDIR/$name.log"
  art="$C930/$artefact"
  rm -f "$art"
  : > "$log"

  # The image the simulation reads comes from the repo's own generator, run here:
  # it is not tracked, and a missing one turns a 25-second test into a 446-second
  # one that fails for a reason no reader of the log can guess.
  prep_rc=0
  if [ "$prep" != - ]; then
    echo "# prep: $prep" >> "$log"
    ( cd "$C930" && timeout "$PREP_TIMEOUT" bash -c "$prep" ) >> "$log" 2>&1
    prep_rc=$?
  fi

  # Bounded on purpose, and the bound takes the whole tree with it: verified on
  # the box that `timeout 5 make quad` returns 124 and leaves no simulator
  # running, because timeout signals the process group make's children are in.
  # A canary that can hang is worse than one that fails.
  started=$(date +%s)
  ( cd "$C930" && timeout "$RUN_TIMEOUT" make "$target" ) >> "$log" 2>&1
  rc=$?
  took=$(( $(date +%s) - started ))

  # The testbench's own end-of-test line, with a non-zero time in it: a
  # simulation that never advanced is not a simulation that finished.
  end=$(grep -aE -- '\$finish called at [1-9]' "$log" | tail -1 || true)

  # Every required line has to be there, matched literally (grep -F): these are
  # the lines themselves, not patterns, and one of them contains brackets.
  got=""
  missing=""
  IFS=';' read -r -a lits <<< "$evidence"
  for lit in "${lits[@]}"; do
    if grep -aFq -- "$lit" "$log"; then
      got="${got}${got:+; }$lit"
    else
      missing="$lit"; break
    fi
  done

  bytes=0
  [ -f "$art" ] && bytes=$(wc -c < "$art" 2>/dev/null | tr -d ' ')
  case "$bytes" in ''|*[!0-9]*) bytes=0 ;; esac

  verdict="PASS"
  why=""
  if [ $prep_rc -ne 0 ]; then
    verdict="FAIL"; why="the generator exited $prep_rc (the image the test reads was not written)"
  elif [ $rc -ne 0 ]; then
    verdict="FAIL"; why="make $target exited $rc"
  elif [ -z "$end" ]; then
    verdict="FAIL"; why="the log has no '\$finish called at <non-zero time>' line: it did not run to the end"
  elif [ -n "$missing" ]; then
    verdict="FAIL"; why="the log is missing: $missing"
  elif [ "$bytes" -eq 0 ]; then
    verdict="FAIL"; why="$artefact was not produced, so the model was never built"
  fi

  if [ "$verdict" = PASS ]; then
    echo "WORK $name: PASS (${got}; ${end#*: }; ${took}s, model $(human_bytes "$bytes"))"
    rows="${rows}| $name | $got | ${took}s | $(human_bytes "$bytes") |
"
    pass=$((pass + 1)); seconds=$((seconds + took))
  else
    echo "WORK $name: FAIL ($why)"
    annotate "$name did not finish: $why -- $(tail -3 "$log" 2>/dev/null | tr '\n' ' ')"
    rows="${rows}| $name | FAIL: $why | ${took}s | |
"
    fail=1
  fi

  if [ "$verdict" != PASS ] && [ -f "$log" ]; then
    echo "      log: $log -- last 6 lines:"
    tail -6 "$log" | sed 's/^/      | /'
  fi
done < <(printf '%s\n' "$WORKLOADS")

verdict=$([ $fail -eq 0 ] && echo PASS || echo FAIL)
[ $fail -ne 0 ] && echo
echo "REAL WORK: $verdict -- $pass finished, $((ran - pass - blocked)) failed, $blocked blocked (of $ran run, ${seconds}s of build and simulation)"

# The same table CI posts: to the step summary when there is one, and to a file
# beside the logs always, so a box run leaves the artifact a CI run leaves too.
{
  echo "## Fast path real work"
  echo
  echo "| workload | evidence | time | model |"
  echo "|---|---|---|---|"
  printf '%s' "$rows"
  echo
  echo "REAL WORK: **$verdict** -- $pass finished, $((ran - pass - blocked)) failed, $blocked blocked (${seconds}s of build and simulation)"
} > "$LOGDIR/real_work_summary.md"
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
  cat "$LOGDIR/real_work_summary.md" >> "$GITHUB_STEP_SUMMARY"
fi
echo "SUMMARY   $LOGDIR/real_work_summary.md"

exit $fail
